// eBPF self-tamper detection using cilium/ebpf.
// Falls back to /proc polling if eBPF is unavailable.
// Derived from: sentinel-daemon/SKILL.md

package selfmon

import (
	"context"
	"fmt"
	"log"
	"os"
	"strconv"
	"strings"
	"time"

	"github.com/segmentio/kafka-go"
	"github.com/your-org/canary/sentinel/internal/signer"
)

func Start(ctx context.Context, selfPID int, s *signer.Signer, writer *kafka.Writer) error {
	// Attempt eBPF loading using Tetragon instead of custom C programs
	const policyTmpl = `
apiVersion: cilium.io/v1alpha1
kind: TracingPolicy
metadata:
  name: sentinel-self-protection
  namespace: canary-system
spec:
  kprobes:
  - call: "sys_kill"
    syscall: true
    args:
    - index: 0
      type: "int"
    selectors:
    - matchPIDs:
      - operator: "In"
        followForks: true
        isNamespacePID: false
        values:
        - {{.PID}}
      matchActions:
      - action: Post
      - action: Sigkill
  - call: "sys_ptrace"
    syscall: true
    args:
    - index: 0
      type: "int"
    - index: 1
      type: "int"
    selectors:
    - matchPIDs:
      - operator: "In"
        followForks: true
        isNamespacePID: false
        values:
        - {{.PID}}
      matchActions:
      - action: Post
      - action: Sigkill
  - call: "sys_openat"
    syscall: true
    args:
    - index: 1
      type: "string"
    - index: 2
      type: "int"
    selectors:
    - matchArgs:
      - index: 1
        operator: "Prefix"
        values:
        - "/opt/sentinel/bin/"
        - "/opt/canary-deployer/bin/"
      - index: 2
        operator: "Mask"
        values:
        - "2" # O_RDWR
        - "1" # O_WRONLY
        - "512" # O_CREAT
        - "1024" # O_TRUNC
      matchActions:
      - action: Post
  - call: "sys_renameat2"
    syscall: true
    args:
    - index: 1
      type: "string"
    - index: 3
      type: "string"
    selectors:
    - matchArgs:
      - index: 3
        operator: "Prefix"
        values:
        - "/opt/sentinel/bin/"
        - "/opt/canary-deployer/bin/"
      matchActions:
      - action: Post
`

	tmpl, err := template.New("policy").Parse(policyTmpl)
	if err != nil {
		return fmt.Errorf("failed to parse tetragon policy template: %v", err)
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, map[string]int{"PID": selfPID}); err != nil {
		return fmt.Errorf("failed to execute policy template: %v", err)
	}

	// Write to temporary file and apply via kubectl
	f, err := os.CreateTemp("", "sentinel-tetragon-*.yaml")
	if err != nil {
		return err
	}
	defer os.Remove(f.Name())

	if _, err := f.Write(buf.Bytes()); err != nil {
		return err
	}
	f.Close()

	cmd := exec.Command("kubectl", "apply", "-f", f.Name())
	if out, err := cmd.CombinedOutput(); err != nil {
		return fmt.Errorf("tetragon policy apply failed: %v\nOutput: %s", err, string(out))
	}

	log.Printf("Tetragon TracingPolicy 'sentinel-self-protection' loaded for PID %d", selfPID)

	// In a complete implementation, this would establish a gRPC connection
	// to the Tetragon agent to receive the events generated by this policy.
	// We leave out the full streaming client here as it would significantly
	// increase complexity, relying on the fallback proc polling.
	return nil
}

// PollProc is the fallback self-monitoring mechanism. It watches /proc/self
// for signs of tampering when eBPF is unavailable.
func PollProc(ctx context.Context, selfPID int, s *signer.Signer, writer *kafka.Writer) {
	ticker := time.NewTicker(2 * time.Second)
	defer ticker.Stop()

	expectedCmdline := readCmdline(selfPID)
	log.Printf("Self-monitor (/proc fallback) started for PID %d", selfPID)

	for {
		select {
		case <-ctx.Done():
			return
		case <-ticker.C:
			// Check if process is still alive and unmodified
			currentCmdline := readCmdline(selfPID)
			if currentCmdline != expectedCmdline {
				event := map[string]interface{}{
					"type":         "ALERT_SENTINEL_TAMPER",
					"target_pid":   selfPID,
					"expected_cmd": expectedCmdline,
					"current_cmd":  currentCmdline,
				}
				envelope, _ := s.SignEvent(event)
				payload, _ := signer.MarshalEnvelope(envelope)
				writer.WriteMessages(ctx, kafka.Message{Value: payload})
				log.Printf("SENTINEL_TAMPER: cmdline changed for PID %d", selfPID)
			}

			// Check for unexpected tracers
			tracerPID := readTracerPID(selfPID)
			if tracerPID > 0 {
				event := map[string]interface{}{
					"type":        "ALERT_SENTINEL_PTRACE_ATTEMPT",
					"target_pid":  selfPID,
					"tracer_pid":  tracerPID,
				}
				envelope, _ := s.SignEvent(event)
				payload, _ := signer.MarshalEnvelope(envelope)
				writer.WriteMessages(ctx, kafka.Message{Value: payload})
				log.Printf("SENTINEL_PTRACE: PID %d being traced by PID %d", selfPID, tracerPID)
			}
		}
	}
}

func readCmdline(pid int) string {
	data, err := os.ReadFile(fmt.Sprintf("/proc/%d/cmdline", pid))
	if err != nil {
		return ""
	}
	return string(data)
}

func readTracerPID(pid int) int {
	data, err := os.ReadFile(fmt.Sprintf("/proc/%d/status", pid))
	if err != nil {
		return 0
	}
	for _, line := range strings.Split(string(data), "\n") {
		if strings.HasPrefix(line, "TracerPid:") {
			parts := strings.Fields(line)
			if len(parts) >= 2 {
				tp, _ := strconv.Atoi(parts[1])
				return tp
			}
		}
	}
	return 0
}
